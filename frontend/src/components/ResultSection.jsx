import {
  CheckCircle,
  GitPullRequest,
  ShieldCheck,
  ShieldAlert,
  ExternalLink,
} from "lucide-react";

const formatNumber = (num) => {
  if (!num) return "0";

  if (num >= 1000000) {
    return (num / 1000000).toFixed(1) + "M";
  }

  if (num >= 1000) {
    return (num / 1000).toFixed(1) + "k";
  }

  return num.toString();
};

const featureNames = {
  la: "Lines Added",
  ld: "Lines Deleted",
  nf: "Files Modified",
  nd: "Directories Modified",
  ns: "Subsystems Modified",
  ent: "Change Entropy",
  ndev: "Developers Involved",
  age: "Code Age",
  nuc: "Unique Changes",
  aexp: "Author Experience",
  arexp: "Recent Experience",
  asexp: "Subsystem Experience",
};


export default function ResultSection({ result }) {
  if (!result) return null;

  const riskColor =
    result.risk === "HIGH"
      ? "text-red-400"
      : result.risk === "MEDIUM"
      ? "text-yellow-400"
      : "text-green-400";

  const riskBg =
    result.risk === "HIGH"
      ? "bg-red-500/10 border-red-500/20"
      : result.risk === "MEDIUM"
      ? "bg-yellow-500/10 border-yellow-500/20"
      : "bg-green-500/10 border-green-500/20";

  return (
    <section className="bg-slate-950 min-h-screen py-20">
      <div className="max-w-7xl mx-auto px-6">

        {/* Heading */}
        <div className="text-center mb-16">
          <h1 className="text-6xl font-black text-white">
            Pull Request Risk Report
          </h1>

          <p className="text-gray-400 mt-4">
            Merge risk assessment generated by the
            JIT Bug Prediction model.
          </p>
        </div>

        {/* Pull Request Overview */}
        <div className="bg-white/5 border border-white/10 rounded-3xl p-8 mb-10">
          <div className="flex items-start gap-4">
            <GitPullRequest className="text-indigo-400 mt-1 shrink-0" />

            <div className="flex-1 min-w-0">
              <p className="text-gray-400">
                {result.repository}
                {result.pull_request?.number && (
                  <span className="ml-2 text-indigo-400">
                    #{result.pull_request.number}
                  </span>
                )}
              </p>

              <h2 className="text-white text-2xl font-bold wrap-break-word mt-1">
                {result.pull_request?.title || "Pull Request"}
              </h2>

              <div className="flex flex-wrap items-center gap-3 mt-4">
                {result.pull_request?.author && (
                  <span className="text-sm bg-slate-900 border border-slate-800 rounded-full px-3 py-1 text-gray-300">
                    by @{result.pull_request.author}
                  </span>
                )}

                {result.pull_request?.head_branch && result.pull_request?.base_branch && (
                  <span className="text-sm bg-slate-900 border border-slate-800 rounded-full px-3 py-1 text-gray-300 font-mono">
                    {result.pull_request.head_branch} → {result.pull_request.base_branch}
                  </span>
                )}

                {result.pull_request?.commits != null && (
                  <span className="text-sm bg-slate-900 border border-slate-800 rounded-full px-3 py-1 text-gray-300">
                    {result.pull_request.commits} commit
                    {result.pull_request.commits === 1 ? "" : "s"}
                  </span>
                )}

                {result.pull_request?.url && (
                  <a
                    href={result.pull_request.url}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="text-sm text-indigo-400 hover:text-indigo-300 flex items-center gap-1"
                  >
                    View on GitHub <ExternalLink size={14} />
                  </a>
                )}
              </div>
            </div>
          </div>
        </div>

        {/* Merge Recommendation */}
        <div
          className={`border rounded-3xl p-8 mb-10 flex items-start gap-4 ${
            result.safe_to_merge
              ? "bg-green-500/10 border-green-500/20"
              : riskBg
          }`}
        >
          {result.safe_to_merge ? (
            <ShieldCheck className="text-green-400 shrink-0 mt-1" size={28} />
          ) : (
            <ShieldAlert className={`${riskColor} shrink-0 mt-1`} size={28} />
          )}

          <div>
            <h2
              className={`text-2xl font-bold ${
                result.safe_to_merge ? "text-green-400" : riskColor
              }`}
            >
              {result.safe_to_merge ? "Safe to Merge" : "Review Recommended"}
            </h2>

            <p className="text-gray-300 mt-2">
              {result.recommendation}
            </p>

            {result.pull_request?.url && (
              <a
                href={result.pull_request.url}
                target="_blank"
                rel="noopener noreferrer"
                className={`inline-flex items-center gap-2 mt-4 px-5 py-2.5 rounded-xl font-semibold transition-all ${
                  result.safe_to_merge
                    ? "bg-green-600 hover:bg-green-700 text-white"
                    : "bg-slate-900 hover:bg-slate-800 text-white border border-slate-700"
                }`}
              >
                {result.safe_to_merge ? "Go to Pull Request & Merge" : "Review Pull Request"}
                <ExternalLink size={16} />
              </a>
            )}
          </div>
        </div>

{/* Repository Statistics */}
<div className="grid md:grid-cols-4 gap-6 mb-10">

  <div className="bg-white/5 border border-white/10 rounded-2xl p-6 hover:border-yellow-400/40 transition">
    <p className="text-gray-400">
      Stars
    </p>

    <h3 className="text-yellow-400 text-3xl font-bold mt-3">
      ⭐ {formatNumber(result.repository_stats?.stars)}
    </h3>
  </div>

  <div className="bg-white/5 border border-white/10 rounded-2xl p-6 hover:border-cyan-400/40 transition">
    <p className="text-gray-400">
      Forks
    </p>

    <h3 className="text-cyan-400 text-3xl font-bold mt-3">
      🍴 {formatNumber(result.repository_stats?.forks)}
    </h3>
  </div>

  <div className="bg-white/5 border border-white/10 rounded-2xl p-6 hover:border-red-400/40 transition">
    <p className="text-gray-400">
      Open Issues
    </p>

    <h3 className="text-red-400 text-3xl font-bold mt-3">
      🐛 {formatNumber(result.repository_stats?.issues)}
    </h3>
  </div>

  <div className="bg-white/5 border border-white/10 rounded-2xl p-6 hover:border-green-400/40 transition">
    <p className="text-gray-400">
      Primary Language
    </p>

    <h3 className="text-green-400 text-3xl font-bold mt-3 wrap-break-word">
      💻 {result.repository_stats?.language || "N/A"}
    </h3>
  </div>

</div>
        {/* Stats Cards */}
        <div className="grid md:grid-cols-3 gap-8 mb-10">

          <div className="bg-white/5 border border-white/10 rounded-3xl p-8">
            <p className="text-gray-400">
              Bug Probability
            </p>

            <h2 className="text-6xl font-black text-white mt-3">
              {result.bug_probability}%
            </h2>
          </div>

          <div className="bg-white/5 border border-white/10 rounded-3xl p-8">
            <p className="text-gray-400">
              Prediction
            </p>

            <h2 className="text-4xl font-bold text-white mt-3">
              {result.prediction === 1
                ? "Bug Prone"
                : "Safe"}
            </h2>
          </div>

          <div
            className={`${riskBg} border rounded-3xl p-8`}
          >
            <p className="text-gray-400">
              Risk Level
            </p>

            <h2
              className={`text-4xl font-bold mt-3 ${riskColor}`}
            >
              {result.risk}
            </h2>
          </div>

        </div>

        {/* Circular Confidence Meter */}
        <div className="bg-white/5 border border-white/10 rounded-3xl p-8 mb-10">
          <h2 className="text-white text-2xl font-bold mb-8">
            Prediction Confidence
          </h2>

          <div className="flex justify-center">
            <div className="relative w-56 h-56">

              <svg
                className="w-56 h-56 -rotate-90"
                viewBox="0 0 100 100"
              >
                {/* Background Circle */}
                <circle
                  cx="50"
                  cy="50"
                  r="40"
                  stroke="#1e293b"
                  strokeWidth="10"
                  fill="none"
                />

                {/* Progress Circle */}
                <circle
                  cx="50"
                  cy="50"
                  r="40"
                  stroke="#6366f1"
                  strokeWidth="10"
                  fill="none"
                  strokeDasharray={`${
                    result.bug_probability * 2.51
                  } 251`}
                  strokeLinecap="round"
                />
              </svg>

              <div className="absolute inset-0 flex items-center justify-center">
                <span className="text-4xl font-black text-white">
                  {result.bug_probability}%
                </span>
              </div>

            </div>
          </div>

          <p className="text-center text-gray-400 mt-6">
            Higher values indicate a greater likelihood
            of defect-prone commits.
          </p>
        </div>

        {/* Pull Request Metrics */}
<div className="bg-white/5 border border-white/10 rounded-3xl p-8 mb-10">
  <h2 className="text-white text-2xl font-bold mb-8">
    Pull Request Metrics
  </h2>

  <div className="grid md:grid-cols-3 gap-6">

    <div className="bg-slate-900 rounded-2xl p-6">
      <p className="text-gray-400">
        Lines Added
      </p>

      <h3 className="text-green-400 text-4xl font-bold mt-3">
        {result.metrics?.la ?? 0}
      </h3>
    </div>

    <div className="bg-slate-900 rounded-2xl p-6">
      <p className="text-gray-400">
        Lines Deleted
      </p>

      <h3 className="text-red-400 text-4xl font-bold mt-3">
        {result.metrics?.ld ?? 0}
      </h3>
    </div>

    <div className="bg-slate-900 rounded-2xl p-6">
      <p className="text-gray-400">
        Files Modified
      </p>

      <h3 className="text-cyan-400 text-4xl font-bold mt-3">
        {result.metrics?.nf ?? 0}
      </h3>
    </div>

    <div className="bg-slate-900 rounded-2xl p-6">
      <p className="text-gray-400">
        Directories Touched
      </p>

      <h3 className="text-indigo-400 text-4xl font-bold mt-3">
        {result.metrics?.nd ?? 0}
      </h3>
    </div>

    <div className="bg-slate-900 rounded-2xl p-6">
      <p className="text-gray-400">
        Subsystems Touched
      </p>

      <h3 className="text-purple-400 text-4xl font-bold mt-3">
        {result.metrics?.ns ?? 0}
      </h3>
    </div>

    <div className="bg-slate-900 rounded-2xl p-6">
      <p className="text-gray-400">
        Change Entropy
      </p>

      <h3 className="text-yellow-400 text-4xl font-bold mt-3">
        {result.metrics?.ent ?? 0}
      </h3>
    </div>

  </div>
</div>

        {/* SHAP Explainability */}
        <div className="bg-white/5 border border-white/10 rounded-3xl p-8 mb-10">
        <h2 className="text-white text-2xl font-bold mb-6">
          SHAP Explainability
        </h2>
        
        <div className="space-y-4">
          {result.shap_insights?.map((item, index) => (
          <div
          key={index}
          className="flex justify-between items-center bg-slate-900 p-4 rounded-xl"
          >
        <span className="text-gray-300">
          {featureNames[item.feature] || item.feature}
        </span>

        <span
          className={
            item.impact > 0
              ? "text-red-400 font-bold"
              : "text-green-400 font-bold"
          }
        >
          {item.impact > 0 ? "+" : ""}
          {item.impact}
        </span>
      </div>
    ))}
  </div>
</div>

        {/* Recommendations */}
        <div className="bg-white/5 border border-white/10 rounded-3xl p-8">
          <h2 className="text-white text-2xl font-bold mb-6">
            Recommendations
          </h2>

          <div className="space-y-5">

            <div className="flex items-center gap-4">
              <CheckCircle className="text-green-400" />

              <p className="text-gray-300">
                Run the test suite against this pull request before merging.
              </p>
            </div>

            <div className="flex items-center gap-4">
              <CheckCircle className="text-green-400" />

              <p className="text-gray-300">
                Review the files with the largest change footprint first.
              </p>
            </div>

            <div className="flex items-center gap-4">
              <CheckCircle className="text-green-400" />

              <p className="text-gray-300">
                Ask a second reviewer to check files touched by multiple contributors.
              </p>
            </div>

          </div>
        </div>

      </div>
    </section>
  );
}
